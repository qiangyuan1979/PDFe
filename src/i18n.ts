/** 翻译错误消息：根据错误 code 返回用户可读的本地化消息，查不到时 fallback 到 fallbackMsg。 */
export function translateError(
  locale: Locale,
  code: string,
  args: Record<string, string> | undefined,
  fallbackMsg: string,
): string {
  const zh = errZh[code];
  if (!zh) return fallbackMsg;
  const base = translate(locale, zh);
  if (!args) return base;
  return base.replace(/\{(\w+)\}/g, (_, k) => (args[k] !== undefined ? args[k] : `{${k}}`));
}

/** 返回当前 locale 对应的翻译函数：组件内 `const t = useT(); t("打开")`。 */
export function useT(): (zh: string, vars?: Record<string, string | number>) => string {
  const locale = useApp((s) => s.locale);
  return (zh, vars) => (vars ? translateFmt(locale, zh, vars) : translate(locale, zh));
}
